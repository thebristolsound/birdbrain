#!/usr/bin/env node
// Lints a PR body against ../template.md. Usage: lint-body.mjs [--any-author] [--posted] <file>
// The file is Markdown, or JSON with a `body` string (a `gh api --input` payload).
// --any-author accepts a body without the attribution line (a human-written PR); the merge
// path uses it. The line, when present, must still be last.
// --posted accepts only GitHub attachment links as screenshots; the merge path uses it, since a
// local path that passes before the PR exists renders as a broken image on GitHub.
// Prints one finding per line and exits 1 on any finding.
import { readFileSync } from 'node:fs'
import { isAbsolute } from 'node:path'
import { parseLayers, plainLanguageFindings, summaryFindings } from './layers.mjs'

// Non-blank top-layer lines; the section headings above Verification take up to nine.
const MAX_LINES_ABOVE_VERIFICATION = 40
const MAX_SUMMARY_SENTENCES = 5
const ATTRIBUTION = 'Pull request description generated by Claude Code'
// The maintainer's global byline, `Created with <model name> in <harness> (<app>)`, where the
// harness and app parts drop out when unknown. Either line is the attribution.
const BYLINE = /^Created with [A-Z][\w.-]*( [\w.-]+)*( in [A-Z][\w.-]*( [\w.-]+)*( \([\w. -]+\))?)?$/
const isAttribution = (l) => l === ATTRIBUTION || BYLINE.test(l)
// Every allowed section, in order; the optional ones may be left out.
const SECTIONS = [
  '## Summary',
  '## Proof',
  '## Screenshots',
  '## Not done',
  '## Blast radius',
  '## Before merge',
  '## After merge',
  '## Changes',
  '## Evidence-affecting',
  '## Verification'
]
const OPTIONAL = ['## Not done', '## Before merge', '## After merge']
const REQUIRED = SECTIONS.filter((s) => !OPTIONAL.includes(s))
const RISK_COLOUR = { High: 'CAUTION', Medium: 'WARNING', Low: 'NOTE', Minimal: 'TIP' }
const RISK_ALERT = /^> \[!(CAUTION|WARNING|NOTE|TIP)\]$/
const RISK_LINE = /^> \*\*Merge risk: (High|Medium|Low|Minimal)\.\*\* \S/
const ATTACHMENT = /^https:\/\/github\.com\/user-attachments\/assets\/[\w-]+$/
// A Markdown image, or the HTML tag GitHub's web editor inserts for an upload.
const IMAGE = /!\[[^\]]*\]\(|<img\b/i
const TABLE_ROW = /^\s*\|.*\|\s*$/
const TABLE_RULE = /^\s*\|(\s*:?-+:?\s*\|)+\s*$/
const IMPACT_FIELDS = [
  'Evidentiary result',
  'What verification proves',
  'Backward verification',
  'Known-answer test'
]
// `source=ci` marks a block verification-from-ci.sh composed from the required checks at head
// (a dependabot or human PR nobody preflighted locally) instead of a `pnpm preflight` run.
const PREFLIGHT_MARKER = /^<!-- preflight v\d+ sha=[0-9a-f]{40} status=\w+( source=\w+)? -->$/
// The footer a cloud-proxy session appends after the body it was given (ADR-0022).
const PLATFORM_FOOTER = /^_?Generated (with|by) \[Claude Code\]\([^)]*\)_?$/
const FORBIDDEN = [
  [/co-authored-by/i, 'a Co-authored-by trailer'],
  [/Generated (with|by) \[Claude Code\]/, 'the platform attribution footer (the attribution line is the only one you author)'],
  [/Summary by CodeRabbit/, 'a CodeRabbit summary (CodeRabbit writes its own; never paste one)']
]

// Template prompts are HTML comments and do not count; the preflight marker is one too and does.
function stripComments(text) {
  return text.replace(/<!--[\s\S]*?-->/g, (m) =>
    /^<!-- preflight /.test(m) ? m : m.split('\n').map(() => '').join('\n')
  )
}

// A platform footer directly after the attribution line was appended by the platform, not
// authored; drop it so the rest of the body is judged as written.
function dropPlatformFooter(text) {
  const lines = text.split('\n')
  let i = lines.length - 1
  while (i >= 0 && lines[i].trim() === '') i--
  if (i < 1 || !PLATFORM_FOOTER.test(lines[i].trim())) return text
  let j = i - 1
  while (j >= 0 && lines[j].trim() === '') j--
  if (j < 0 || !isAttribution(lines[j].trim())) return text
  return lines.slice(0, j + 1).join('\n') + '\n'
}

function countSentences(text) {
  const prose = text
    .replace(/`[^`]*`/g, '')
    .replace(/\d+\.\d+/g, '')
    .replace(/\b(e\.g|i\.e|vs|etc)\./gi, '')
  return (prose.match(/[.!?](?=\s|$)/g) || []).length
}

function screenshotFindings(lines, posted) {
  const declarations = lines.filter((line) => /^\s*- Visual changes:/i.test(line))
  if (declarations.length !== 1) {
    return ['Screenshots needs one "- Visual changes: Yes" or "- Visual changes: No. <reason>" declaration']
  }
  const declaration = declarations[0].trim()
  const no = declaration.match(/^- Visual changes: No\.\s+(\S.*)$/i)
  const images = lines.filter((line) => IMAGE.test(line))
  if (no) {
    return images.length ? ['Visual changes is No but Screenshots contains screenshot images'] : []
  }
  if (!/^- Visual changes: Yes\s*$/i.test(declaration)) {
    return ['Visual changes must say Yes, or No followed by a reason']
  }

  const findings = []
  const screens = new Map()
  for (const line of lines) {
    if (IMAGE.test(line) && !/^\s*- (Before|After),/i.test(line)) {
      findings.push(`every screenshot is a Before or After row; found: "${line.trim().slice(0, 60)}"`)
      continue
    }
    if (!/^\s*- (Before|After),/i.test(line)) continue
    const shot = line.match(/^\s*- (Before|After), (.+?): !\[[^\]]*\]\((<[^>]+>|[^)]+)\)\s*$/i)
    if (!shot) {
      findings.push('each Before/After row needs an image; a screenshot handoff is not evidence')
      continue
    }
    const [, phase, screen, reference] = shot
    const path = reference.replace(/^<|>$/g, '')
    const key = screen.trim().toLowerCase()
    const pair = screens.get(key) ?? new Map()
    const side = phase.toLowerCase()
    if (pair.has(side)) findings.push(`duplicate ${side} screenshot for ${screen}`)
    pair.set(side, path)
    screens.set(key, pair)
    if (ATTACHMENT.test(path)) continue
    if (posted) {
      findings.push(`${phase}, ${screen}: upload the screenshot; a posted body links GitHub attachments only`)
      continue
    }
    if (!isAbsolute(path)) {
      findings.push(`${phase}, ${screen}: use a GitHub attachment or an absolute path to a captured PNG`)
      continue
    }
    try {
      const png = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])
      if (!readFileSync(path).subarray(0, png.length).equals(png)) {
        findings.push(`${phase}, ${screen}: the local screenshot is not a PNG`)
      }
    } catch {
      findings.push(`${phase}, ${screen}: the local screenshot cannot be read: ${path}`)
    }
  }
  if (!screens.size) findings.push('Visual changes is Yes but no before/after screenshot pair is supplied')
  for (const [screen, pair] of screens) {
    if (!pair.has('before') || !pair.has('after')) {
      findings.push(`${screen} needs both Before and After rows with the same screen name`)
    } else if (pair.get('before') === pair.get('after')) {
      findings.push(`${screen} needs separate before and after screenshots`)
    }
  }
  return findings
}

// An escaped pipe (\|) is cell text, not a column break.
const cells = (row) => row.trim().replace(/^\||\|$/g, '').split(/(?<!\\)\|/).map((c) => c.trim())

// Rows of every table in `lines` except each table's header and rule rows.
function tableRows(lines) {
  const rows = []
  let header = true
  for (const l of lines) {
    if (!TABLE_ROW.test(l)) {
      header = true
      continue
    }
    if (header || TABLE_RULE.test(l)) {
      header = false
      continue
    }
    rows.push(cells(l))
  }
  return rows
}

export function lintBody(raw, { anyAuthor = false, posted = false } = {}) {
  const findings = []
  const text = dropPlatformFooter(raw.replace(/\r\n/g, '\n'))
  const lines = text.split('\n')
  const visibleText = stripComments(text).split('\n')
  // A line that stripping emptied was a template prompt; it is not authored text.
  const fromComment = lines.map((l, i) => l.trim() !== '' && visibleText[i].trim() === '')

  for (const [re, what] of FORBIDDEN) {
    if (re.test(text)) findings.push(`body contains ${what}`)
  }

  // The two layers: `top[i]` is true for a line outside every <details> block.
  const layers = parseLayers(visibleText)
  findings.push(...layers.findings)
  const top = layers.visible
  const inBlock = (i) => !top[i]

  const firstIdx = visibleText.findIndex((l) => l.trim() !== '')
  const first = (visibleText[firstIdx] || '').trim()
  if (!/^Closes #\d+(, #\d+)*$/.test(first) && !/^No issue: \S.*$/.test(first)) {
    findings.push(`line 1 must be "Closes #N" (or "No issue: <reason>"), got: "${first.slice(0, 60)}"`)
  }

  const headings = []
  visibleText.forEach((l, i) => {
    if (/^#{1,6} /.test(l)) headings.push({ line: i, text: l.trim() })
  })
  const h2 = headings.filter((h) => h.text.startsWith('## ')).map((h) => h.text)
  const order = h2.map((h) => SECTIONS.indexOf(h))
  const inOrder = order.every((k, i) => k >= 0 && (i === 0 || k > order[i - 1]))
  if (!inOrder || REQUIRED.some((r) => !h2.includes(r))) {
    findings.push(
      `sections must be ${REQUIRED.join(', ')} in that order, with ${OPTIONAL.join(', ')} allowed where the template puts them; got: ${h2.join(', ') || '(none)'}`
    )
  }
  for (const h of headings) {
    if (h.text.startsWith('# ')) findings.push(`no top-level heading: "${h.text}"`)
    if (h.text.startsWith('### ') && h.text !== '### Evidence impact') {
      findings.push(`no subsections except "### Evidence impact": "${h.text}"`)
    }
    if (/^#{4,} /.test(h.text)) findings.push(`no deep headings: "${h.text}"`)
  }

  const start = (name) => visibleText.findIndex((l, i) => top[i] && l.trim() === name)
  const section = (name) => {
    const s = start(name)
    if (s < 0) return null
    let e = visibleText.findIndex((l, i) => i > s && top[i] && /^## /.test(l))
    if (e < 0) e = visibleText.length
    const indexes = [...Array(e - s - 1).keys()].map((k) => s + 1 + k)
    return { start: s, end: e, lines: visibleText.slice(s + 1, e), indexes }
  }
  const blocksWithin = (sec) => layers.blocks.filter((b) => b.start > sec.start && b.end < sec.end)
  const topText = (sec) => sec.indexes.filter((i) => top[i] && visibleText[i].trim() !== '')
  const blockBody = (b) => b.lines.slice(b.lines.findIndex((l) => /<summary>/i.test(l)) + 1)

  // The Merge risk notice sits between line 1 and the Summary, and its colour is its level.
  const summaryIdx = start('## Summary')
  const notice = visibleText
    .slice(firstIdx + 1, summaryIdx < 0 ? firstIdx + 1 : summaryIdx)
    .map((l) => l.trim())
    .filter((l, k) => l !== '' && top[firstIdx + 1 + k])
  const alert = (notice[0] || '').match(RISK_ALERT)
  const level = (notice[1] || '').match(RISK_LINE)
  if (notice.length !== 2 || !alert || !level) {
    findings.push(
      'between line 1 and Summary goes the Merge risk notice: "> [!CAUTION]" (or WARNING, NOTE, TIP), then "> **Merge risk: High.** <what merging ships>"'
    )
  } else if (RISK_COLOUR[level[1]] !== alert[1]) {
    findings.push(`Merge risk ${level[1]} takes the [!${RISK_COLOUR[level[1]]}] alert, not [!${alert[1]}]`)
  }

  const summary = section('## Summary')
  if (summary) {
    // The merge commit ends the Summary at its first <details> block, so nothing may follow it.
    const firstBlock = blocksWithin(summary)[0]
    const cut = firstBlock ? firstBlock.start : summary.end
    const after = summary.indexes.filter((i) => i > cut && top[i] && visibleText[i].trim() !== '')
    if (after.length) {
      findings.push(`Summary text after the Diagram block is left out of the merge commit; move it above: "${visibleText[after[0]].trim().slice(0, 60)}"`)
    }
    const n = countSentences(summary.indexes.filter((i) => i < cut && top[i]).map((i) => visibleText[i]).join(' '))
    if (n > MAX_SUMMARY_SENTENCES) findings.push(`Summary has ${n} sentences; the cap is ${MAX_SUMMARY_SENTENCES}`)
    if (n === 0) findings.push('Summary is empty')
  }

  const proof = section('## Proof')
  if (proof) {
    const outside = topText(proof)
    if (outside.length) {
      findings.push(`Proof is one <details> block; found text outside it: "${visibleText[outside[0]].trim().slice(0, 60)}"`)
    }
    const body = blocksWithin(proof).flatMap(blockBody)
    if (!body.some((l) => /^Head: `?[0-9a-f]{7,40}`?\./.test(l.trim()))) {
      findings.push('Proof names the head commit: "Head: `<sha>`. Merge gate: <link or pending>."')
    }
    if (!body.some((l) => /^\|\s*Acceptance criterion\s*\|\s*Proof\s*\|\s*Result\s*\|$/.test(l.trim()))) {
      findings.push('Proof holds the "| Acceptance criterion | Proof | Result |" table')
    } else {
      const rows = tableRows(body)
      const open = rows.find((r) => r.length !== 3 || r.some((c) => c === ''))
      if (!rows.length) findings.push('Proof has no filled row; a criterion nothing proves goes under Not done')
      else if (open) {
        findings.push(`Proof row "${open[0].slice(0, 40)}" lacks a proof or result; a criterion nothing proves goes under Not done`)
      }
    }
  }

  const shots = section('## Screenshots')
  if (shots) findings.push(...screenshotFindings(shots.lines, posted))
  const stray = visibleText.findIndex((l, i) => IMAGE.test(l) && !(shots && i > shots.start && i < shots.end))
  if (stray >= 0) findings.push(`line ${stray + 1}: images go in the Screenshots section, never elsewhere in the body`)

  const notDone = section('## Not done')
  if (notDone) {
    const text = topText(notDone).map((i) => visibleText[i])
    if (!text.length) findings.push('Not done is empty; delete the section when there is nothing to list')
    const prose = text.find((l) => !/^\s*- \S/.test(l))
    if (prose) findings.push(`Not done holds only bullets; found: "${prose.trim().slice(0, 60)}"`)
  }

  const blast = section('## Blast radius')
  if (blast) {
    const text = topText(blast).map((i) => visibleText[i].trim())
    if (text.length !== 2 || !/^- On merge: \S/.test(text[0] || '') || !/^- If wrong: \S/.test(text[1] || '')) {
      findings.push('Blast radius is two filled bullets, "- On merge: <what ships>" then "- If wrong: <what breaks, how to back out>"')
    }
  }

  for (const name of ['## Before merge', '## After merge']) {
    const sec = section(name)
    if (!sec) continue
    const text = topText(sec).map((i) => visibleText[i])
    const bad = text.find((l) => !/^\s*- \[[ x]\] \S/i.test(l))
    if (!text.length || bad) {
      findings.push(`${name.slice(3)} holds one filled "- [ ] <step, owner>" checkbox per step; delete the section when there is none`)
    }
  }

  const changes = section('## Changes')
  if (changes) {
    const outside = topText(changes)
    if (outside.length) {
      findings.push(`Changes is <details> blocks of file groups and decisions; found text outside them: "${visibleText[outside[0]].trim().slice(0, 60)}"`)
    }
    const blocks = blocksWithin(changes)
    if (!blocks.length) {
      findings.push('Changes has no <details> block; the file groups are collapsed under a plain <summary>')
    } else {
      const body = blocks.flatMap(blockBody)
      const bad = body.filter((l) => l.trim() !== '' && !/^\s*- /.test(l) && !TABLE_ROW.test(l))
      if (bad.length) findings.push(`Changes holds only bullets or table rows; found prose: "${bad[0].trim().slice(0, 60)}"`)
      const files = blockBody(blocks[0])
      const filled = files.some((l) => /^\s*- \S/.test(l)) || tableRows(files).some((r) => r.some((c) => c !== ''))
      if (!filled) findings.push('Changes lists no file group')
    }
  }

  const evidence = section('## Evidence-affecting')
  if (evidence) {
    const answerIdx = evidence.indexes.find((i) => visibleText[i].trim() !== '')
    const answer = answerIdx === undefined ? '' : visibleText[answerIdx].trim()
    if (answer !== 'Yes' && answer !== 'No') {
      findings.push(`Evidence-affecting must answer "Yes" or "No" on its first line, got: "${answer.slice(0, 40)}"`)
    }
    const impactIdx = evidence.indexes.find((i) => visibleText[i].trim() === '### Evidence impact')
    const hasImpact = impactIdx !== undefined
    if (answer === 'Yes') {
      if (!hasImpact) findings.push('Evidence-affecting is Yes but "### Evidence impact" is missing')
      else if (!inBlock(impactIdx)) findings.push('"### Evidence impact" and its four fields sit inside a <details> block')
      const body = evidence.lines.join('\n')
      for (const f of IMPACT_FIELDS) {
        if (!body.includes(f)) findings.push(`Evidence impact is missing the "${f}" field`)
      }
    } else if (hasImpact) {
      findings.push('Evidence-affecting is No but carries an Evidence impact subsection')
    }
  }

  const vStart = start('## Verification')
  if (vStart >= 0) {
    const above = visibleText
      .slice(0, vStart)
      .filter((l, i) => top[i] && !fromComment[i] && l.trim() !== '' && !PREFLIGHT_MARKER.test(l.trim()))
    if (above.length > MAX_LINES_ABOVE_VERIFICATION) {
      findings.push(`${above.length} non-blank lines above ## Verification; the cap is ${MAX_LINES_ABOVE_VERIFICATION}`)
    }
    if (above.some((l) => /^\s*```/.test(l))) {
      findings.push('fenced output above ## Verification; test output and figures live only in the Verification block')
    }
    const before = (visibleText[vStart - 1] || '').trim()
    const within = visibleText.slice(vStart + 1).some((l) => PREFLIGHT_MARKER.test(l.trim()))
    if (!PREFLIGHT_MARKER.test(before) && !within) {
      findings.push('Verification lacks the <!-- preflight v1 sha=... status=... --> marker; paste .preflight/verification.md verbatim')
    }
    const vBlocks = layers.blocks.filter((b) => b.start > vStart)
    if (!vBlocks.length) {
      findings.push('Verification holds the preflight block inside a <details> block; paste .preflight/verification.md verbatim, it is written that way')
    }
    const loose = visibleText
      .slice(vStart + 1)
      .map((l, k) => ({ l: l.trim(), i: vStart + 1 + k }))
      .filter(({ l, i }) => top[i] && l !== '' && !isAttribution(l) && !PREFLIGHT_MARKER.test(l))
    if (loose.length) {
      findings.push(`line ${loose[0].i + 1}: Verification text outside the <details> block: "${loose[0].l.slice(0, 60)}"`)
    }
  }

  const last = ([...visibleText].reverse().find((l) => l.trim() !== '') || '').trim()
  const hasAttribution = visibleText.some((l) => isAttribution(l.trim()))
  if (hasAttribution && !isAttribution(last)) {
    findings.push('the attribution line must be the last line')
  } else if (!hasAttribution && !anyAuthor) {
    findings.push(`the last line must be exactly "${ATTRIBUTION}" or a "Created with <model name> in <harness> (<app>)" byline`)
  }

  // The top layer is plain language. Protocol lines are exempt: line 1, the section
  // headings, the Yes/No answer, the preflight marker and the attribution line.
  const exempt = (i, l) => {
    const t = l.trim()
    return (
      i === firstIdx ||
      SECTIONS.includes(t) ||
      RISK_ALERT.test(t) ||
      t === 'Yes' ||
      t === 'No' ||
      isAttribution(t) ||
      PREFLIGHT_MARKER.test(t) ||
      fromComment[i]
    )
  }
  findings.push(...plainLanguageFindings(visibleText, top, exempt))
  findings.push(...summaryFindings(layers.blocks))

  return findings
}

function bodyFromFile(path) {
  const raw = readFileSync(path, 'utf8')
  if (path.endsWith('.json') || /^\s*\{/.test(raw)) {
    try {
      const j = JSON.parse(raw)
      if (typeof j.body === 'string') return j.body
    } catch {
      // not JSON after all; lint it as Markdown
    }
  }
  return raw
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  const args = process.argv.slice(2)
  const anyAuthor = args.includes('--any-author')
  const posted = args.includes('--posted')
  const file = args.find((a) => !a.startsWith('--'))
  if (!file) {
    console.error('usage: lint-body.mjs [--any-author] [--posted] <file>')
    process.exit(2)
  }
  const findings = lintBody(bodyFromFile(file), { anyAuthor, posted })
  for (const f of findings) console.log(`- ${f}`)
  process.exit(findings.length ? 1 : 0)
}
